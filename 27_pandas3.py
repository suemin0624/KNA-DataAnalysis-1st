import pandas as pd

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 전체 평균 온도
print(df["온도"].mean().round(3))  # 45.339

# 냉각기 상태별 평균 온도
print(df.groupby("냉각기상태")["온도"].mean().round(3))
# 냉각기상태
# 고장    54.668
# 저하    45.465
# 정상    35.885

# 분산 구하기
print(df.groupby("냉각기상태")["온도"].var().round(3))
# 냉각기상태
# 고장    14.135
# 저하     2.147
# 정상     0.126

# 평균과 분산 결과를 종합해서 보가
# 1. 고장 : 높은 평균 온도 + 개별 온도는 더 들쑥날쑥
# 2. 저하 : 전체평균과 비슷한 평균온도 + 많이 모여있는 개별 온도
# 3. 정상 : 전체평균보다 확실히 낮은 평균온도 + 평균에 거의 집중된 개별 온도

# 표준편차 구하기
print(df.groupby("냉각기상태")["온도"].std().round(3))
# 냉각기상태
# 고장    3.760
# 저하    1.465
# 정상    0.356

# 평균과 표준편차를 종합해서 살펴보기
# 고장 54.668 +/- 3.760 정도에 개별 값이 모여있음
# 저하 45.465 +/- 1.465 정도에 개별 값이 모여있음
# 정상 35.885 +/- 0.356 정도에 개별 값이 모여있음

# 중앙값 찾기
print(df.groupby("냉각기상태")["온도"].median().round(3))
# 냉각기상태  평균         중앙값
# 고장     54.668      55.45
# 저하     45.465      44.90
# 정상     35.885      35.90

# agg : aggregate (집계하다)
# 여러 개의 통계 계산을 한 번에 시키는 메서드

# agg()에서 자주 쓰는 집계 함수
# mean : 평균
# sum : 합계
# count : 개수 (결측값 제외)
# size : 행 개수
# min : 최솟값
# max : 최댓값
# std : 표준편차
# var : 분산
# median : 중앙값

# 앞선 내용처럼 냉각기상태별 평균 온도를 출력
print(df.groupby("냉각기상태")["온도"].mean().round(2))
# 냉각기상태
# 고장    54.67
# 저하    45.46
# 정상    35.89

# 냉각기상태별 온도의 표준편차 출력
print(df.groupby("냉각기상태")["온도"].std().round(2))
# 냉각기상태
# 고장    3.76
# 저하    1.47
# 정상    0.36

# 냉각기상태별 온도의 평균과 표준편차를 한 번에 정리하기
print(df.groupby("냉각기상태")["온도"].agg(["mean", "std"]).round(2))
#         mean   std
# 냉각기상태
# 고장     54.67  3.76
# 저하     45.46  1.47
# 정상     35.89  0.36

# 위 방식으로 묶어서 결과를 보니 mean, std, ... 일반인은 잘 모를듯
# 그래서 다른 이름들로 항목이 나타나게 만들자!
print(
    df.groupby("냉각기상태")
    .agg(
        평균온도=("온도", "mean"),
        온도편차=("온도", "std"),
        평균진동=("진동", "mean"),
        측정수=("온도", "count"),
    )
    .round(2)
)
#         평균온도  온도편차  평균진동  측정수
# 냉각기상태
# 고장     54.67  3.76  0.69   40
# 저하     45.46  1.47  0.61   40
# 정상     35.89  0.36  0.55   40

""" 실습 1) 평균/분산/표준편차 구하기 """
import pandas as pd

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")
# 전체와 라인별로 평균/분산/표준편차 구하기
# 대푯값(평균)과 흩어짐(분산/표준편차)을 나타내는 세 통계량 구하기

# 진동 열 전체와 평균/분산/표준편차를 각각 구하기
print(df["진동"].mean().round(3))  # 0.616
print(round(df["진동"].var(), 3))  # 0.004
print(round(df["진동"].std(), 3))  # 0.064

# 표준편차를 제곱하면 분산과 같아지는지 확인
print(0.064 * 0.064)

# 라인(냉각기상태별)으로 그룹을 나눠 라인별 평균과 표준편차 비교
print(df.groupby("냉각기상태")["진동"].mean().round(3))
# 고장    0.688
# 저하    0.610
# 정상    0.549

print(df.groupby("냉각기상태")["진동"].std().round(3))
# 냉각기상태
# 고장    0.048
# 저하    0.010
# 정상    0.009

# 한 번에 모아보기
print(df.groupby("냉각기상태")["진동"].agg(["mean", "std"]).round(3))
#         mean    std
# 냉각기상태
# 고장     0.688  0.048
# 저하     0.610  0.010
# 정상     0.549  0.009

# 판다스가 더 권장하는 방식으로 통계 항목별 이름 붙여 정리하기
print(
    df.groupby("냉각기상태")
    .agg(평균=("진동", "mean"), 표준편차=("진동", "std"))
    .round(3)
)
# 냉각기상태
# 고장     0.688  0.048
# 저하     0.610  0.010
# 정상     0.549  0.009

